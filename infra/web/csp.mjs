// Content-Security-Policy of the viewer and the studio, computed while building the web image:
// the hashes of the inline <script> blocks (the theme bootstrap) of each built index.html, so
// no inline script runs unless it is exactly the one we shipped.
//
//   node infra/web/csp.mjs apps/viewer/dist/index.html apps/studio/dist/index.html > csp.caddy
//
// Prints Caddyfile snippets (csp_viewer, csp_studio) that infra/Caddyfile imports.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";

const [viewerHtml, studioHtml] = process.argv.slice(2);
if (!viewerHtml || !studioHtml) {
  console.error("usage: node csp.mjs <viewer index.html> <studio index.html>");
  process.exit(2);
}

/** 'sha256-…' of every inline script (no src): exactly the text between the tags. */
function inlineScriptHashes(file) {
  const html = readFileSync(file, "utf8");
  const hashes = new Set();
  for (const [, attributes, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
    if (/\bsrc\s*=/i.test(attributes) || body.length === 0) continue;
    hashes.add(`'sha256-${createHash("sha256").update(body, "utf8").digest("base64")}'`);
  }
  return [...hashes];
}

function policy(hashes, frameAncestors) {
  return [
    "default-src 'self'",
    ["script-src 'self'", ...hashes].join(" "),
    // Inline styles: MapLibre, Photo Sphere Viewer and React set them at runtime.
    "style-src 'self' 'unsafe-inline'",
    // Room icons are picked from Iconify in the studio (preview images and the SVG itself).
    "img-src 'self' data: blob: https://api.iconify.design",
    // Recorded capture videos are previewed from blob: URLs.
    "media-src 'self' blob:",
    "worker-src 'self' blob:",
    // Map glyphs (fonts) come from protomaps; everything else is same-origin.
    "connect-src 'self' https://protomaps.github.io https://api.iconify.design",
    "font-src 'self' data:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    `frame-ancestors ${frameAncestors}`,
  ].join("; ");
}

const viewer = policy(inlineScriptHashes(viewerHtml), "*");
const studio = policy(inlineScriptHashes(studioHtml), "'none'");

process.stdout.write(`# Generated by infra/web/csp.mjs while building the web image. Do not edit.
(csp_viewer) {
\theader Content-Security-Policy "${viewer}"
}

(csp_studio) {
\theader Content-Security-Policy "${studio}"
\theader Cross-Origin-Opener-Policy "same-origin"
}
`);
